// Generates docs/CODEMAP.md: one line per source file with its exports.
// AI agents read this one file instead of opening or grepping src/.
// Run: pnpm codemap   (re-run after adding, renaming or removing exports)
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SRC = join(ROOT, 'src');

const walk = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : e.name.endsWith('.ts') ? [join(dir, e.name)] : [],
  );

const EXPORT_RE = /^export\s+(?:declare\s+)?(?:default\s+)?(?:abstract\s+)?(?:const enum|const|let|function\*?|class|interface|type|enum)\s+([A-Za-z0-9_$]+)/gm;
const LIST_RE = /^export\s*\{([^}]+)\}/gm;

const byDir = new Map();
for (const file of walk(SRC).sort()) {
  const text = readFileSync(file, 'utf8');
  const names = [];
  for (const m of text.matchAll(EXPORT_RE)) names.push(m[1]);
  for (const m of text.matchAll(LIST_RE)) {
    for (const part of m[1].split(',')) {
      const n = part.trim().split(/\s+as\s+/).pop();
      if (n) names.push(n);
    }
  }
  const rel = relative(SRC, file).split(sep).join('/');
  const dir = rel.includes('/') ? rel.slice(0, rel.lastIndexOf('/')) : '.';
  const lines = text.split('\n').length - 1;
  if (!byDir.has(dir)) byDir.set(dir, []);
  byDir.get(dir).push({ name: rel.slice(dir === '.' ? 0 : dir.length + 1), lines, names });
}

let out = '# CODEMAP (generated by `pnpm codemap`, do not edit by hand)\n\n';
out += 'Format: `file (lines): exports`. Paths are relative to `src/`.\n';
for (const [dir, files] of byDir) {
  out += `\n## ${dir}/\n`;
  for (const f of files) {
    out += `- ${f.name} (${f.lines}): ${f.names.length ? f.names.join(', ') : '-'}\n`;
  }
}
mkdirSync(join(ROOT, 'docs'), { recursive: true });
writeFileSync(join(ROOT, 'docs', 'CODEMAP.md'), out);
console.log(`docs/CODEMAP.md written (${out.length} chars)`);
